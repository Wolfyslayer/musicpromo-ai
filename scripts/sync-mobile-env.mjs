#!/usr/bin/env node
/**
 * Sync web Vite env → Expo EXPO_PUBLIC_* for local Google OAuth testing.
 *
 * Usage:
 *   node scripts/sync-mobile-env.mjs           # write mobile/.env from root .env.local
 *   node scripts/sync-mobile-env.mjs --check   # validate only (no write)
 *   node scripts/sync-mobile-env.mjs --doctor  # validate + probe Edge Functions
 *
 * Google sign-in needs hosted Supabase Edge Functions (registerGoogleOAuthPkce,
 * googleAuthExchange). The local Cloud Agent Supabase stack does not run them.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const MOBILE_ENV = resolve(ROOT, "mobile/.env");
const DEFAULT_APP_ORIGIN = "https://musicpromoai.site";
const REDIRECT_PATH = "/auth/google/callback";

const args = new Set(process.argv.slice(2));
const checkOnly = args.has("--check");
const doctor = args.has("--doctor");

function parseEnvFile(path) {
  if (!existsSync(path)) return null;
  const out = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function firstExistingEnv(...paths) {
  for (const p of paths) {
    const parsed = parseEnvFile(p);
    if (parsed) return { path: p, env: parsed };
  }
  return null;
}

function pick(env, ...keys) {
  for (const k of keys) {
    const v = String(env[k] || "").trim();
    if (v) return v;
  }
  return "";
}

function isLocalSupabaseUrl(url) {
  try {
    const u = new URL(url);
    return (
      u.hostname === "127.0.0.1" ||
      u.hostname === "localhost" ||
      u.hostname === "0.0.0.0" ||
      u.hostname.endsWith(".local")
    );
  } catch {
    return false;
  }
}

function mask(value) {
  if (!value) return "(empty)";
  if (value.length <= 12) return "***";
  return `${value.slice(0, 6)}…${value.slice(-4)}`;
}

const root = firstExistingEnv(
  resolve(ROOT, ".env.local"),
  resolve(ROOT, ".env"),
  resolve(ROOT, "mobile/.env")
);

if (!root) {
  console.error(
    "No env file found. Create root .env.local with VITE_SUPABASE_URL, VITE_SUPABASE_ANON_KEY, VITE_GOOGLE_CLIENT_ID (see docs/GOOGLE_SIGNIN.md)."
  );
  process.exit(1);
}

const source = root.env;
const supabaseUrl = pick(source, "EXPO_PUBLIC_SUPABASE_URL", "VITE_SUPABASE_URL");
const anonKey = pick(source, "EXPO_PUBLIC_SUPABASE_ANON_KEY", "VITE_SUPABASE_ANON_KEY");
const googleClientId = pick(source, "EXPO_PUBLIC_GOOGLE_CLIENT_ID", "VITE_GOOGLE_CLIENT_ID");
const appOrigin = pick(
  source,
  "EXPO_PUBLIC_APP_ORIGIN",
  "VITE_APP_ORIGIN",
  "PUBLIC_APP_URL",
  "VITE_PUBLIC_APP_URL"
).replace(/\/$/, "") || DEFAULT_APP_ORIGIN;
const redirectUri = `${appOrigin}${REDIRECT_PATH}`;

const lines = [
  "# Generated by scripts/sync-mobile-env.mjs — do not commit.",
  `# Source: ${root.path.replace(ROOT + "/", "")}`,
  `# Generated: ${new Date().toISOString()}`,
  "",
  `EXPO_PUBLIC_SUPABASE_URL=${supabaseUrl}`,
  `EXPO_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  `EXPO_PUBLIC_GOOGLE_CLIENT_ID=${googleClientId}`,
  `EXPO_PUBLIC_APP_ORIGIN=${appOrigin}`,
  "",
];

console.log(`Source: ${root.path}`);
console.log(`Supabase URL: ${supabaseUrl || "(missing)"}`);
console.log(`Anon key: ${mask(anonKey)}`);
console.log(`Google client ID: ${mask(googleClientId)}`);
console.log(`App origin: ${appOrigin}`);
console.log(`Google redirect URI: ${redirectUri}`);
console.log("");

const problems = [];
if (!supabaseUrl) problems.push("Missing VITE_SUPABASE_URL / EXPO_PUBLIC_SUPABASE_URL");
if (!anonKey) problems.push("Missing VITE_SUPABASE_ANON_KEY / EXPO_PUBLIC_SUPABASE_ANON_KEY");
if (!googleClientId) {
  problems.push(
    "Missing VITE_GOOGLE_CLIENT_ID / EXPO_PUBLIC_GOOGLE_CLIENT_ID (Web OAuth client)"
  );
}
if (supabaseUrl && isLocalSupabaseUrl(supabaseUrl)) {
  problems.push(
    "Supabase URL is local — Edge Functions (googleAuthExchange / registerGoogleOAuthPkce) are not available on the Cloud Agent local stack. Point at your hosted project to test Google OAuth."
  );
}
if (googleClientId && !googleClientId.endsWith(".apps.googleusercontent.com")) {
  problems.push("Google client ID does not look like a Web client (*.apps.googleusercontent.com)");
}

if (!checkOnly && !doctor) {
  writeFileSync(MOBILE_ENV, lines.join("\n"), "utf8");
  console.log(`Wrote ${MOBILE_ENV.replace(ROOT + "/", "")}`);
} else if (checkOnly || doctor) {
  const mobile = parseEnvFile(MOBILE_ENV);
  if (!mobile) {
    console.log("mobile/.env not found yet — run without --check to generate it.");
  } else {
    const ok =
      pick(mobile, "EXPO_PUBLIC_SUPABASE_URL") === supabaseUrl &&
      pick(mobile, "EXPO_PUBLIC_GOOGLE_CLIENT_ID") === googleClientId;
    console.log(
      ok
        ? "mobile/.env matches source mapping."
        : "mobile/.env is stale — re-run: npm run mobile:sync-env"
    );
  }
}

async function probeFunction(name) {
  const url = `${supabaseUrl.replace(/\/$/, "")}/functions/v1/${name}`;
  try {
    const res = await fetch(url, {
      method: "POST",
      headers: {
        apikey: anonKey,
        Authorization: `Bearer ${anonKey}`,
        "Content-Type": "application/json",
      },
      body: "{}",
    });
    const text = await res.text();
    let body = text;
    try {
      body = JSON.stringify(JSON.parse(text));
    } catch {
      /* keep raw */
    }
    return { name, status: res.status, body: body.slice(0, 180) };
  } catch (e) {
    return { name, status: 0, body: e.message };
  }
}

if (doctor) {
  if (!supabaseUrl || !anonKey) {
    console.error("\nDoctor skipped: need Supabase URL + anon key.");
    process.exit(1);
  }
  console.log("Probing Edge Functions (expect 4xx JSON, not 404)...\n");
  const results = await Promise.all([
    probeFunction("registerGoogleOAuthPkce"),
    probeFunction("googleAuthExchange"),
  ]);
  for (const r of results) {
    const ok = r.status > 0 && r.status !== 404;
    console.log(`${ok ? "✓" : "✗"} ${r.name} → HTTP ${r.status || "ERR"} ${r.body}`);
    if (!ok) {
      problems.push(
        `Function ${r.name} not reachable — deploy with: supabase functions deploy ${r.name}`
      );
    }
  }
  console.log("");
  console.log("Checklist:");
  console.log(
    "  [ ] Google Cloud → Web client → Authorized redirect URIs includes exactly:"
  );
  console.log(`      ${redirectUri}`);
  console.log("  [ ] Supabase → Auth → Google enabled with same Client ID (+ secret)");
  console.log(
    "  [ ] Supabase secrets: GOOGLE_CLIENT_SECRET or GOOGLE_LOGIN_CLIENT_SECRET"
  );
  console.log("  [ ] Functions deployed: registerGoogleOAuthPkce, googleAuthExchange");
  console.log("  [ ] mobile/.env synced; restart Expo after env changes");
}

if (problems.length) {
  console.error("\nIssues:");
  for (const p of problems) console.error(`  • ${p}`);
  process.exit(doctor || checkOnly ? 1 : 0);
}

console.log("\nOK — env ready for Expo Google OAuth (hosted Supabase).");
console.log("Next: cd mobile && npx expo start");
